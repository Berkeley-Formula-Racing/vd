function config = vdRampConfig()
%VDRAMPCONFIG Adapt shared defaults to the existing ramp-speed setup schema.
shared = vdVehicleConfig();
tire = vdTireConfig();
vehicle = struct();
vehicle.mass = shared.car.mass;
vehicle.accel_driver_weight = shared.car.accel_driver_weight;
vehicle.wheelbase = shared.car.wheelbase;
vehicle.weight_dist = shared.car.weight_dist;
vehicle.track_width = shared.car.track_width;
vehicle.wheel_radius = shared.car.wheel_radius;
vehicle.cg_height = shared.car.cg_height;
vehicle.roll_center_height_front = shared.car.roll_center_height_front;
vehicle.roll_center_height_rear = shared.car.roll_center_height_rear;
vehicle.I_zz = shared.car.I_zz;
vehicle.ackermann = shared.car.ackermann;
vehicle.camber_compliance_f = shared.car.camber_compliance_f;
vehicle.camber_compliance_r = shared.car.camber_compliance_r;
vehicle.static_r_toe = shared.car.static_r_toe;
vehicle.roll_gradient_deg_per_g = shared.car.roll_gradient_deg_per_g;
vehicle.rear_roll_camber_outer_deg_per_deg = shared.car.rear_roll_camber_outer_deg_per_deg;
vehicle.rear_roll_camber_inner_deg_per_deg = shared.car.rear_roll_camber_inner_deg_per_deg;
vehicle.ride_camber_front_deg_per_in = shared.car.ride_camber_front_deg_per_in;
vehicle.ride_camber_rear_deg_per_in = shared.car.ride_camber_rear_deg_per_in;
vehicle.I_wheel = shared.car.I_wheel;
vehicle.I_driveline = shared.car.I_driveline;
vehicle.Crr = shared.car.Crr;
vehicle.qss_steering_limit_deg = shared.car.qss_steering_limit_deg;
vehicle.motion_ratio_front = shared.car.motion_ratio_front;
vehicle.motion_ratio_rear = shared.car.motion_ratio_rear;
% The b26 aero map uses front/rear offsets at the axle stations. The physical
% ride-height measurements are taken at the CAD stations below, so translate
% the nominal CAD line to x=0 and x=wheelbase before defining the baseline.
cad_front_x_in = shared.ramp.cad_front_x_in;
cad_rear_x_in = shared.ramp.cad_rear_x_in;
cad_front_z_in = shared.ramp.cad_front_z_in;
cad_rear_z_in = shared.ramp.cad_rear_z_in;
front_axle_x_in = 0;
rear_axle_x_in = vehicle.wheelbase/0.0254;
cad_slope_in_per_in = (cad_rear_z_in-cad_front_z_in)/ ...
    (cad_rear_x_in-cad_front_x_in);
vehicle.map_reference_front_ride_height_in = cad_front_z_in + ...
    cad_slope_in_per_in*(front_axle_x_in-cad_front_x_in);
vehicle.map_reference_rear_ride_height_in = cad_rear_z_in + ...
    cad_slope_in_per_in*(rear_axle_x_in-cad_rear_x_in);

vehicle.accel_cda = shared.aero.accel_cda;
vehicle.accel_cla = shared.aero.accel_cla;
vehicle.aero_distribution = shared.aero.distribution;
vehicle.accel_cla_p_deg_p = shared.aero.acc_cla_p_deg_p;
vehicle.accel_D_p_deg_p = shared.aero.acc_D_p_deg_p;
vehicle.redline = shared.engine.redline;
vehicle.shift_point = shared.engine.shift_point;
vehicle.gears = shared.engine.gears;
vehicle.primary_reduction = shared.engine.primary_reduction;
vehicle.torque_fn = shared.engine.torque_fn();
vehicle.shift_time = shared.engine.shift_time;
vehicle.final_drive = shared.drivetrain.final_drive;
vehicle.drivetrain_efficiency = shared.drivetrain.drivetrain_efficiency;
vehicle.G_d1 = shared.drivetrain.G_d1;
vehicle.G_d2_overrun = shared.drivetrain.G_d2_overrun;
vehicle.G_d2_driving = shared.drivetrain.G_d2_driving;
vehicle.brake_distribution = shared.brakes.brake_distribution;
vehicle.max_braking_torque = shared.brakes.max_braking_torque;
vehicle.gamma_f = tire.gamma_f;
vehicle.gamma_r = tire.gamma_r;
vehicle.p_i = tire.p_i;
vehicle.Fx_parameters = tire.Fx_parameters;
vehicle.Fy_parameters = tire.Fy_parameters;
vehicle.friction_scaling_factor = tire.friction_scaling_factor;
vehicle.grip_scaling_front = tire.grip_scaling_front;
vehicle.grip_scaling_rear = tire.grip_scaling_rear;

% The current acceleration setup has no front ARB; keep this fixed while the
% rear ARB remains the discrete setup factor.
fixed = struct('vehicle',vehicle,'frontArbStiffness_NmPerRad',shared.ramp.frontArbStiffness_NmPerRad);
config = struct( ...
    'schemaVersion',1, ...
    'baselineVersion',"ramp-baseline-3", ...
    'id',"ramp-baseline", ...
    'label',"Ramp-speed baseline", ...
    'source',"carConfigBaseline", ...
    'fixedParameters',fixed, ...
    'defaultMapPath',shared.aero.map_path);

% The master owns available choices and default spring/ARB settings.
config.options = struct( ...
    'rearArbStiffness_NmPerRad',shared.ramp.rearArbOptions_NmPerRad, ...
    'frontSpringRate_lb_in',shared.ramp.frontSpringOptions_lb_in, ...
    'rearSpringRate_lb_in',shared.ramp.rearSpringOptions_lb_in);
config.defaults = struct( ...
    'rearArbStiffness_NmPerRad',shared.ramp.rearArbStiffness_NmPerRad, ...
    'frontSpringRate_lb_in',shared.car.spring_rate_front_lb_in, ...
    'rearSpringRate_lb_in',shared.car.spring_rate_rear_lb_in, ...
    'frontRideHeight_in',vehicle.map_reference_front_ride_height_in, ...
    'rearRideHeight_in',vehicle.map_reference_rear_ride_height_in, ...
    'aeroMapId',"b26", ...
    'driverWeight_kg',vehicle.accel_driver_weight, ...
    'rearWeightDistribution_percent',vehicle.weight_dist*100);
config.defaultSetup = struct( ...
    'schemaVersion',1, ...
    'baselineVersion',config.baselineVersion, ...
    'id',config.id, ...
    'label',config.label, ...
    'source',config.source, ...
    'aeroMapId',config.defaults.aeroMapId, ...
    'driverWeight_kg',config.defaults.driverWeight_kg, ...
    'rearWeightDistribution_percent',config.defaults.rearWeightDistribution_percent, ...
    'rearArbStiffness_NmPerRad',config.defaults.rearArbStiffness_NmPerRad, ...
    'frontSpringRate_lb_in',config.defaults.frontSpringRate_lb_in, ...
    'rearSpringRate_lb_in',config.defaults.rearSpringRate_lb_in, ...
    'frontRideHeight_in',config.defaults.frontRideHeight_in, ...
    'rearRideHeight_in',config.defaults.rearRideHeight_in, ...
    'isBaseline',true);
end
