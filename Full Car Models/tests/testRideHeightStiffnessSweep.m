function tests = testRideHeightStiffnessSweep
testDir = fileparts(mfilename('fullpath'));
addpath(genpath(fileparts(testDir)));
tests = functiontests(localfunctions);
end

function testPreviewBuildsCartesianGridInsideAeroMapBounds(testCase)
options = struct( ...
    'preview',true, ...
    'numRideLevels',3, ...
    'frontSpringRates_lb_in',[250 300], ...
    'rearSpringRates_lb_in',[200 250], ...
    'bootstrap',false);

preview = run_ride_height_stiffness_sweep(options);

verifyEqual(testCase,preview.mapBounds.front,[-0.45 0.30],'AbsTol',1e-12);
verifyEqual(testCase,preview.mapBounds.rear,[-0.30 0.45],'AbsTol',1e-12);
verifyEqual(testCase,height(preview.designTable),36);
verifyEqual(testCase, ...
    unique(preview.designTable.static_front_ride_height_in), ...
    linspace(-0.45,0.30,3).','AbsTol',1e-12);
verifyEqual(testCase, ...
    unique(preview.designTable.static_rear_ride_height_in), ...
    linspace(-0.30,0.45,3).','AbsTol',1e-12);
verifyTrue(testCase,all(preview.designTable.static_front_ride_height_in >= -0.45));
verifyTrue(testCase,all(preview.designTable.static_front_ride_height_in <= 0.30));
verifyTrue(testCase,all(preview.designTable.static_rear_ride_height_in >= -0.30));
verifyTrue(testCase,all(preview.designTable.static_rear_ride_height_in <= 0.45));
end

function testPreviewRejectsRideHeightOutsideAeroMap(testCase)
options = struct( ...
    'preview',true, ...
    'frontRideHeights_in',[-0.46 0], ...
    'rearRideHeights_in',[-0.30 0.45], ...
    'bootstrap',false);

verifyError(testCase,@() run_ride_height_stiffness_sweep(options), ...
    'run_ride_height_stiffness_sweep:rideHeightOutsideAeroMap');
end

function testOneCaseRunsAndWritesCompactOutputs(testCase)
outputDirectory = tempname;
mkdir(outputDirectory);
cleanup = onCleanup(@() rmdir(outputDirectory,'s')); %#ok<NASGU>

options = struct( ...
    'bootstrap',false, ...
    'frontRideHeights_in',0, ...
    'rearRideHeights_in',0, ...
    'frontSpringRates_lb_in',300, ...
    'rearSpringRates_lb_in',250, ...
    'numWorkers',0, ...
    'plot',false, ...
    'verbose',false, ...
    'outputDirectory',outputDirectory, ...
    'outputPath',fullfile(outputDirectory,'one_case.mat'), ...
    'overwrite',true);

result = run_ride_height_stiffness_sweep(options);

verifyEqual(testCase,height(result.caseTable),1);
verifyEqual(testCase,height(result.metricTable),1);
verifyTrue(testCase,isfile(result.output.matPath));
verifyTrue(testCase,isfile(result.output.csvPath));
loaded = load(result.output.matPath,'designTable','caseTable','metricTable', ...
    'rawResults');
verifyEqual(testCase,height(loaded.designTable),1);
verifyEqual(testCase,height(loaded.caseTable),1);
verifyEqual(testCase,height(loaded.metricTable),1);
verifyEmpty(testCase,loaded.rawResults);
end

