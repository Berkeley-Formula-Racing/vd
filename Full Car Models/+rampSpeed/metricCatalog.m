    "perSpeed","power_limited",[],"flag","flag",1, ...
    "power limited","Validity","Power limit active",false,"stairs",@allRows);
catalog(end+1) = makeMetric("aero_outside_map","validity",["lateral","longitudinal"], ...
    "perSpeed","aero_outside_map",[],"flag","flag",1, ...
    "aero outside map","Validity","Aero map status",false,"stairs",@allRows);

catalog(end+1) = makeMetric("raw_aLat","raw","lateral", ...
    "points","aLat_mps2",[],"m/s^2","g",1/9.80665, ...
    "raw a_y (g)","Raw ramp points","Lateral acceleration",false,"markers",@validRows);
catalog(end+1) = makeMetric("raw_aLong","raw","longitudinal", ...
    "points","aLong_mps2",[],"m/s^2","g",1/9.80665, ...
    "raw a_x (g)","Raw ramp points","Longitudinal acceleration",false,"markers",@validRows);
catalog(end+1) = makeMetric("raw_steer","raw","lateral", ...
    "points","steer_rad",[],"rad","deg",180/pi, ...
    "raw steer (deg)","Raw ramp points","Steering",false,"markers",@validRows);
catalog(end+1) = makeMetric("raw_yaw_rate","raw","lateral", ...
    "points","yaw_rate_rps",[],"rad/s","rps",1/(2*pi), ...
    "raw yaw rate (rps)","Raw ramp points","Yaw rate",false,"markers",@validRows);

if isfield(options,'type') && ~isempty(options.type)
    requestedType = lower(string(options.type));
elseif isfield(options,'validType') && ~isempty(options.validType)
    requestedType = lower(string(options.validType));
else
    requestedType = "";
end
if strlength(requestedType) > 0
    keep = arrayfun(@(s) any(s.validTypes == requestedType) || ...
        any(s.validTypes == "any"),catalog);
    catalog = catalog(keep);
end
end

function spec = makeMetric(id,tab,validTypes,sourceLevel,field,derivation, ...
    storedUnits,displayUnits,scale,yLabel,titleText,subtitle,zeroLine,style,validityRule)
spec = metricTemplate();
spec.id = id;
spec.tab = tab;
spec.validTypes = validTypes;
spec.sourceLevel = sourceLevel;
spec.field = field;
spec.derivation = derivation;
spec.storedUnits = storedUnits;
spec.displayUnits = displayUnits;
spec.scale = scale;
spec.yLabel = yLabel;
spec.title = titleText;
spec.subtitle = subtitle;
spec.zeroLine = zeroLine;
spec.seriesStyle = struct('style',string(style),'lineStyle',"-", ...
    'marker',"none",'lineWidth',1.5,'markerSize',6);
spec.validityRule = validityRule;
end

function spec = metricTemplate()
spec = struct('id',"",'tab',"",'validTypes',strings(0,1), ...
    'sourceLevel',"",'field',"",'derivation',[], ...
    'storedUnits',"",'displayUnits',"",'scale',1,'yLabel',"", ...
    'title',"",'subtitle',"",'zeroLine',false,'seriesStyle',struct(), ...
    'validityRule',@validRows);
end

function mask = validRows(T)
if istable(T) && ismember('valid',T.Properties.VariableNames)
    mask = logical(T.valid);
else
    mask = true(height(T),1);
end
mask = mask(:);
end

function mask = allRows(T)
mask = true(height(T),1);
end
