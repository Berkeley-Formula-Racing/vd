function catalog = metricCatalog(options)
%METRICCATALOG Describe the metrics exposed by the ramp-speed UI.

if nargin < 1 || isempty(options)
    options = struct();
end

catalog = repmat(metricTemplate(),0,1);

catalog(end+1) = makeMetric("capability_free","capability","lateral", ...
    "perSpeed","aLat_free_mps2",[],"m/s^2","g",1/9.80665, ...
    "a_y free (g)","Free lateral capability","",false,"line",@validRows);
