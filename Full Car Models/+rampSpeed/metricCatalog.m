    "perSpeed","front_ride_height_m",[],"m","in",39.37007874015748, ...
    "front ride height (in)","Ride and suspension","Front axle",false,"line",@validRows);
catalog(end+1) = makeMetric("rear_ride_height","ride",["lateral","longitudinal"], ...
    "perSpeed","rear_ride_height_m",[],"m","in",39.37007874015748, ...
    "rear ride height (in)","Ride and suspension","Rear axle",false,"line",@validRows);
catalog(end+1) = makeMetric("front_camber","ride",["lateral","longitudinal"], ...
    "perSpeed","front_camber_rad",@(T) T.front_camber_rad,"rad","deg",180/pi, ...
    "front camber (deg)","Ride and suspension","Front axle",false,"line",@validRows);
catalog(end+1) = makeMetric("rear_camber","ride",["lateral","longitudinal"], ...
    "perSpeed","rear_camber_rad",@(T) T.rear_camber_rad,"rad","deg",180/pi, ...
    "rear camber (deg)","Ride and suspension","Rear axle",false,"line",@validRows);
