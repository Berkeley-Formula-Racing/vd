    "perSpeed","aLat_sustainable_mps2",[],"m/s^2","g",1/9.80665, ...
    "a_y sustainable (g)","Sustainable lateral capability","",false,"line",@validRows);
catalog(end+1) = makeMetric("ramp_complete","capability",["lateral","longitudinal"], ...
    "perSpeed","ramp_complete_fraction",[],"fraction","%",100, ...
    "ramp completion (%)","Ramp completion","",false,"line",@validRows);

catalog(end+1) = makeMetric("aero_front_load","aero",["lateral","longitudinal"], ...
    "perSpeed","front_downforce_N",[],"N","N",1, ...
    "front aero load (N)","Aerodynamic load","Front axle",false,"line",@validRows);
catalog(end+1) = makeMetric("aero_rear_load","aero",["lateral","longitudinal"], ...
    "perSpeed","rear_downforce_N",[],"N","N",1, ...
    "rear aero load (N)","Aerodynamic load","Rear axle",false,"line",@validRows);
catalog(end+1) = makeMetric("downforce","aero",["lateral","longitudinal"], ...
    "perSpeed","downforce_N",[],"N","N",1, ...
    "downforce (N)","Aerodynamic load","Total",false,"line",@validRows);
catalog(end+1) = makeMetric("drag","aero",["lateral","longitudinal"], ...
    "perSpeed","drag_N",[],"N","N",1, ...
    "drag (N)","Aerodynamic load","Total",false,"line",@validRows);
catalog(end+1) = makeMetric("aero_balance","aero",["lateral","longitudinal"], ...
    "perSpeed","aero_balance_front",[],"fraction","%",100, ...
    "front aero balance (%)","Aerodynamic balance","Front fraction",false,"line",@validRows);
catalog(end+1) = makeMetric("mechanical_balance","balance","lateral", ...
    "perSpeed","mechanical_balance_front",[],"fraction","%",100, ...
    "mechanical balance (%)","Mechanical balance","Front fraction",false,"line",@validRows);
catalog(end+1) = makeMetric("handling_balance","balance","lateral", ...
    "perSpeed","K_linear_rad_per_mps2",@(T) T.K_linear_rad_per_mps2, ...
    "rad/(m/s^2)","deg/g",9.80665*180/pi, ...
    "K_{linear} (deg/g)","Handling balance","Linear understeer gradient",true,"line",@validRows);
catalog(end+1) = makeMetric("yaw_balance","balance","lateral", ...
    "perSpeed","cuo_steer_linear_rad",@(T) T.cuo_steer_linear_rad, ...
