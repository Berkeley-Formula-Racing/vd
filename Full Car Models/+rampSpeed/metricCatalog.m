    "perSpeed","pitch_rad",[],"rad","deg",180/pi, ...
    "pitch angle (deg)","Ride and suspension","Body pitch",false,"line",@validRows);
catalog(end+1) = makeMetric("front_shock_travel","ride",["lateral","longitudinal"], ...
    "perSpeed","front_shock_travel_m",[],"m","in",39.37007874015748, ...
    "front shock travel (in)","Ride and suspension","Front axle",false,"line",@validRows);
catalog(end+1) = makeMetric("rear_shock_travel","ride",["lateral","longitudinal"], ...
    "perSpeed","rear_shock_travel_m",[],"m","in",39.37007874015748, ...
    "rear shock travel (in)","Ride and suspension","Rear axle",false,"line",@validRows);

