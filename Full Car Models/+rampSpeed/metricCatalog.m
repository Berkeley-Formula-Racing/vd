    "perSpeed","valid",[],"flag","flag",1, ...
    "validity","Validity","Solver validity",false,"stairs",@allRows);
catalog(end+1) = makeMetric("truncated","validity",["lateral","longitudinal"], ...
    "perSpeed","truncated",[],"flag","flag",1, ...
    "truncated","Validity","Ramp truncated",false,"stairs",@allRows);
